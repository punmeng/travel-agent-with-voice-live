export const getLocale = () => locale;
export function setLocale(value) {
  locale = value === 'en-US' ? 'en-US' : 'zh-TW';
  document.documentElement.lang = locale;
}
export function t(key, values = {}) {
  const text = locale === 'en-US' ? catalog[key] ?? key : key;
  return text.replace(/\{(\w+)\}/g, (match, name) => Object.hasOwn(values, name) ? String(values[name]) : match);
}
export function bindText(node, key, values = {}) {
  node.dataset.i18n = key;
  node.dataset.i18nValues = JSON.stringify(values);
  node.textContent = t(key, values);
  return node;
}
export function applyTranslations(root = document) {
  for (const node of root.querySelectorAll('[data-i18n]')) node.textContent = t(node.dataset.i18n,
    node.dataset.i18nValues ? JSON.parse(node.dataset.i18nValues) : {});
  for (const attr of ['aria-label', 'placeholder', 'content']) {
    for (const node of root.querySelectorAll(`[data-i18n-${attr}]`)) node.setAttribute(attr, t(node.getAttribute(`data-i18n-${attr}`)));
  }
}
